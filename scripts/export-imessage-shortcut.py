"""Write the iPhone Bridge Shortcut guide and its unsigned workflow plist into docs/imessage.

Usage: .venv/Scripts/python scripts/export-imessage-shortcut.py
Both come from artist_lead_finder.imessage.shortcut, so they match the app's guide.
"""

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "backend"))

from artist_lead_finder.imessage import shortcut

OUT = ROOT / "docs" / "imessage"
PLIST = "Verse iPhone Bridge.unsigned.plist"

HEAD = """# iPhone Bridge: Shortcut для отправки iMessage

> Файл создаётся скриптом `scripts/export-imessage-shortcut.py` из
> `backend/artist_lead_finder/imessage/shortcut.py`. Правьте шаги там, а не здесь.

## Как это работает

1. **iMessage → Кампании**: получатели (телефон `+15555550123` или email), варианты сообщений
   (раздаются по очереди, `{Phone}` подставляет получателя), файлы.
2. **«Рассылка через телефон»** сама включает мост (адрес Wi-Fi/Ethernet, не VPN; все запросы
   требуют временный токен на 12 часов) и открывает окно с QR-кодом запуска. Адрес, порт, токен и
   имена команд — в «Настройках» рассылки; там же «Тест на один номер».
3. Отсканируйте QR-код запуска камерой iPhone. Ссылка
   `shortcuts://run-shortcut?name=…&input=text&text=…` откроет «Команды» и запустит команду
   с адресом задания на входе. Приложение ничего не открывает на телефоне само.

## Два протокола

| | Исходный «Verse iMessage» | Новый «Verse iPhone Bridge» |
|---|---|---|
| Запрос | `GET /task` — вся кампания за раз | `GET /v2/next` — одно задание |
| Подтверждение | `GET /ack` сразу после текста, до вложений | `textAckUrl` после текста, `ackUrl` после текста **и** всех файлов |
| Пауза / остановка | не действуют на уже выданный список | между заданиями: `paused` — ждать `retrySeconds`, `stopped`/`finished` — выход |
| Пауза между номерами | случайная 20–50 с внутри команды | фиксированная `delaySeconds` из приложения |
| Общий `message` | извлекается, но не отправляется | подставляется вместо пустого индивидуального текста на стороне приложения |

Исходная команда работает с `/task` без изменений. Новый протокол исходной командой не
поддерживается: для него команду нужно собрать заново по шагам ниже.

## Статусы в приложении

- **В очереди** (`pending`) — телефон задание ещё не получал.
- **Выдано телефону** (`issued`) — задание у Shortcut; автоматически повторно не выдаётся.
- **Выполнено на iPhone** (`execution_acknowledged`) — Shortcut подтвердил свои шаги. Это
  **не** подтверждение доставки: Команды его не дают. У исходной команды это значит только
  «шаг отправки текста пройден».
- **Неизвестно** (`uncertain`) — сообщение могло уйти, но подтверждение не пришло (истёк срок,
  телефон запросил следующее задание без ACK, приложение перезапускалось). Повторно не
  отправляется; решите вручную: «Ушло», «Не ушло» или «В очередь снова».
- **Не отправлено** (`failed`) — вы отметили, что сообщение не ушло.

Повторный ACK ничего не меняет. ACK, пришедший после «Неизвестно», переводит задание в
«Выполнено» и убирает его из очереди.

## Разрешения и ограничения iOS

- **Окно отправки.** В обоих действиях «Отправить сообщение» явно включено «Показывать при
  выполнении» (`ShowWhenRun = true`): iOS показывает окно сообщения, отправка — после вашего
  нажатия. Если выключить, при первом запуске iOS спросит, разрешить ли команде отправлять
  сообщения; выберите «Всегда разрешать». Пропадут ли подтверждения полностью, зависит от
  версии iOS — проверьте тестом на свой номер.
- **iMessage или SMS.** Штатное действие отправляет через Сообщения: iMessage, если номер
  зарегистрирован в iMessage, иначе SMS (если она включена: Настройки → Сообщения →
  «Отправить как SMS»). Выбрать iMessage принудительно действие не позволяет.
- **Экран.** Работа при заблокированном экране не гарантирована. Держите iPhone разблокированным
  и «Команды» на экране, пока идёт рассылка; при необходимости временно поставьте
  «Автоблокировка: никогда».
- **Сеть.** iPhone и компьютер в одной Wi-Fi сети; в брандмауэре Windows разрешите
  `artist-core` для частных сетей.
- **Файлы.** В действии отправки файла поле «Сообщение» должно содержать только переменную
  «Содержимое URL» с типом **Файл**. Если поставить её рядом с текстом или пробелом, Команды
  превратят файл в текстовое описание. Сервер отдаёт файлы с `Content-Type` и
  `Content-Disposition`, поэтому «Получить содержимое URL» возвращает файл с именем и типом.

## Установка

iPhone импортирует только подписанные файлы `.shortcut`, а подписать их можно только на Mac.
Поэтому команду собирают вручную по шагам ниже. Рядом лежит
`{plist}` — та же команда в виде неподписанного workflow plist. Это исходник для
сверки и для подписи на Mac. На iPhone он **не** устанавливается, и переименование в
`.shortcut` этого не меняет.

## Сборка нового Shortcut

Создайте команду с именем, указанным в приложении (по умолчанию **Verse iPhone Bridge**).
Имя должно совпадать буква в букву. Вывод действия переименовывается нажатием на него →
«Переименовать». Отступ показывает вложенность (в цикл или условие).

| № | Действие | WFWorkflowActionIdentifier | В исходном |
|---|---|---|---|
"""

TAIL = """
## Проверка на iPhone

1. Включите мост, добавьте свой номер, «Тест на один номер».
2. Отсканируйте QR-код запуска и подтвердите отправку в окне Сообщений.
3. В журнале должны появиться «Выдано», «Текст», «Выполнено», а в Сообщениях — текст и
   каждый файл отдельным сообщением (как файл, не как текст со ссылкой).
4. Проверьте паузу: запустите рассылку на 2–3 своих номера, нажмите «Пауза» после первого —
   команда должна ждать, после «Продолжить» — продолжить.
"""


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    rows = []
    for step in shortcut.guide():
        indent = "&nbsp;&nbsp;&nbsp;&nbsp;" * step["depth"]
        text = step["text"].replace("|", "\\|")
        notes = "".join(f"<br>*{note}*" for note in step["notes"])
        original = str(step["original"]) if step["original"] else "—"
        rows.append(
            f"| {step['number']} | {indent}{text}{notes} | `{step['identifier']}` | {original} |"
        )
    guide = HEAD.replace("{plist}", f"`{PLIST}`") + "\n".join(rows) + "\n" + TAIL
    (OUT / "SHORTCUT.md").write_text(guide, encoding="utf-8", newline="\n")
    (OUT / PLIST).write_bytes(shortcut.unsigned_plist())
    print(f"{OUT / 'SHORTCUT.md'}\n{OUT / PLIST}")


if __name__ == "__main__":
    main()
